/* ── Shared dispatch core ─────────────────────────────────────────────────
 * Both the text protocol and the binary opcode frame resolve to a registry
 * entry and then run it here, so the access gate and the handler call live in
 * exactly one place. */

static const struct shell_cmd *find_by_opcode(uint8_t opcode)
{
    if (opcode == OP_INVALID) {
        return NULL;
    }
    for (int i = 0; commands[i].name != NULL; i++) {
        if (commands[i].opcode == opcode) {
            return &commands[i];   /* first match wins (aliases share an opcode) */
        }
    }
    return NULL;
}

static void run_command(const struct shell_cmd *c, char *args)
{
    if (mesh_is_dispatch_thread()) {
        /* Over the air: the PDU's CMAC already proved fleet membership, so the
         * per-connection secauth gate does not apply. Only commands explicitly
         * marked broadcast-safe may run from a flood. */
        if (c->flags & CMD_MESH) {
            c->handler(args);
        }
        return;
    }

    /* Access gate: when enforcement is on, only NOAUTH commands (AUTH, SYSINFO)
     * run until the peer authenticates this connection. */
    if (secauth_enforced() && !secauth_is_authed() &&
        !(c->flags & CMD_NOAUTH)) {
        ble_printf("ERR:auth required (send AUTH)\r\n");
        return;
    }

    c->handler(args);
}

/* Prefix-match a text line to a registry entry, returning the entry and the
 * argument substring. Shared by the text dispatcher and BCAST (which re-uses it
 * to turn "BCAST all MODE:3" into the MODE opcode + "3" payload). */
static const struct shell_cmd *match_line(const char *line, const char **args_out)
{
    for (int i = 0; commands[i].name != NULL; i++) {
        const char *cmd = commands[i].name;

        /* One-byte reject before the calls. The registry is 54 entries and
         * "FW:" sits 32 of them in, so a frame upload — 62-313 lines, each
         * re-walking the table — was paying a strlen() plus a strncmp() call
         * per entry per line, thousands of them per frame. Comparing the first
         * character first drops all but the handful of entries that share it,
         * and cannot change the outcome: a differing first byte already
         * guarantees strncmp() is non-zero for any non-empty name. */
        if (cmd[0] != line[0]) continue;

        int cmd_len = (int)strlen(cmd);

        if (strncmp(line, cmd, cmd_len) != 0) continue;

        const char *args = line + cmd_len;
        char last = cmd[cmd_len - 1];

        /* Commands ending with ':' or '=' consume everything after the
         * separator; others require args to be absent or space-separated. */
        if (last != ':' && last != '=' && *args != '\0' && *args != ' ') continue;

        while (*args == ' ') args++;
        *args_out = args;
        return &commands[i];
    }
    return NULL;
}

/* Resolve a binary opcode frame to its handler. The single dispatch point that
 * the mesh layer (Phase 1) will also call for flooded commands. */
void cmd_dispatch_opcode(uint8_t opcode, char *args, enum cmd_origin origin)
{
    /* `origin` is not stored yet: Phase 1 will route replies by it, but a
     * single file-scope variable would be the wrong home — the mesh dispatch
     * thread and the BLE RX thread dispatch concurrently and would clobber
     * each other's value. It belongs in a per-dispatch context. */
    ARG_UNUSED(origin);

    const struct shell_cmd *c = find_by_opcode(opcode);
    if (c) {
        run_command(c, args ? args : "");
    } else {
        ble_printf("ERR:bad opcode %02X\r\n", opcode);
    }
}

/* ── Dispatch a single complete text line ────────────────────────────────── */

/* ── DFU busy gate ──────────────────────────────────────────────────────
 *
 * While an image is being transferred the BLE link is the transfer. Web
 * Bluetooth cannot run two GATT operations at once, and on our side every
 * text command runs on the BLE RX thread — a command that takes the display
 * lock, waits on a panel refresh or queues notifications behind a saturated
 * TX pool stalls the SMP exchange that is in flight, and the phone reports
 * "GATT operation failed for unknown reason" and aborts the update.
 *
 * So for the duration of a transfer the dispatcher accepts only what the
 * update itself needs — DFU:, REBOOT, SYSINFO, HOST: — and answers everything
 * else with one short BUSY:dfu line. The window opens on DFU:START or on the
 * first SMP upload chunk (mcumgr hook, so a host that never says DFU:START is
 * covered too) and closes on DFU:DONE, on the upload finishing or aborting,
 * on disconnect, or after ten idle minutes if the host simply vanished. */
static bool dfu_busy;
static struct k_work_delayable dfu_busy_timeout;
#define DFU_BUSY_TIMEOUT K_MINUTES(10)

static void dfu_busy_expire(struct k_work *work)
{
    ARG_UNUSED(work);
    dfu_busy = false;
}

static void dfu_set_busy(bool on)
{
    dfu_busy = on;
    if (on) {
        k_work_reschedule(&dfu_busy_timeout, DFU_BUSY_TIMEOUT);
    } else {
        k_work_cancel_delayable(&dfu_busy_timeout);
    }
}

static bool allowed_while_dfu(const char *line)
{
    return strncmp(line, "DFU:", 4) == 0 ||
           strcmp(line, "REBOOT") == 0 ||
           strncmp(line, "SYSINFO", 7) == 0 ||
           strncmp(line, "HOST:", 5) == 0;
}

#ifdef CONFIG_MCUMGR_MGMT_NOTIFICATION_HOOKS
static enum mgmt_cb_return dfu_mgmt_cb(uint32_t event, enum mgmt_cb_return prev_status,
                                       int32_t *rc, uint16_t *group, bool *abort_more,
                                       void *data, size_t data_size)
{
    ARG_UNUSED(prev_status); ARG_UNUSED(rc); ARG_UNUSED(group);
    ARG_UNUSED(abort_more); ARG_UNUSED(data); ARG_UNUSED(data_size);

    switch (event) {
    case MGMT_EVT_OP_IMG_MGMT_DFU_STARTED:
        dfu_set_busy(true);
        break;
    case MGMT_EVT_OP_IMG_MGMT_DFU_CHUNK:
        if (dfu_busy) {
            k_work_reschedule(&dfu_busy_timeout, DFU_BUSY_TIMEOUT);
        }
        break;
    case MGMT_EVT_OP_IMG_MGMT_DFU_STOPPED:
    case MGMT_EVT_OP_IMG_MGMT_DFU_PENDING:
        dfu_set_busy(false);
        break;
    default:
        break;
    }
    return MGMT_CB_OK;
}

static struct mgmt_callback dfu_mgmt_callback = {
    .callback = dfu_mgmt_cb,
    .event_id = MGMT_EVT_OP_IMG_MGMT_ALL,
};
#endif

static void dispatch_line(const char *line)
{
    const char *args = "";
    if (dfu_busy && !allowed_while_dfu(line)) {
        ble_printf("BUSY:dfu\r\n");
        return;
    }
    const struct shell_cmd *c = match_line(line, &args);
    if (c) {
        run_command(c, (char *)args);   /* text is an alias for the entry's opcode */
    } else {
        ble_printf("unknown cmd\r\n");
    }
}

