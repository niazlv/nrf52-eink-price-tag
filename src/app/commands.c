/* ── Hex helpers ─────────────────────────────────────────────────────────── */

static int hex_nibble(char c)
{
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static int hex_byte(const char *s)
{
    int hi = hex_nibble(s[0]);
    int lo = hex_nibble(s[1]);
    if (hi < 0 || lo < 0) return -1;
    return (hi << 4) | lo;
}

/* Shared "offset:HH.." prologue of FW:, RW: and LW:. Returns the hex payload
 * and writes *offset, or NULL when the colon separator is missing. An offset
 * that does not fit an int comes back as -1 so range_ok() rejects it. */
static const char *parse_offset_prefix(char *args, int *offset)
{
    char *endptr;
    long value = strtol(args, &endptr, 10);

    if (*endptr != ':') {
        return NULL;
    }
    *offset = (value < 0 || value > INT_MAX) ? -1 : (int)value;
    return endptr + 1;
}

/* True when writing nbytes at offset stays inside a limit-sized buffer.
 * Phrased as (offset <= limit - nbytes), NOT (offset + nbytes > limit): offset
 * arrives straight off the wire and can be INT_MAX, where that addition is
 * signed overflow — it wraps negative and the naive check passes. */
static bool range_ok(int offset, int nbytes, int limit)
{
    return offset >= 0 && nbytes >= 0 && nbytes <= limit && offset <= limit - nbytes;
}

/* ── Vstream helpers ─────────────────────────────────────────────────────── */

/* CRC-16/CCITT-FALSE (poly 0x1021, init 0xFFFF, MSB-first) — running update.
 * Must match the host's crc16_ccitt().
 *
 * Nibble table, not the byte table the RAM budget can't afford and not the
 * table-free shift loop that came before it: 16 entries is 32 bytes of .rodata
 * and zero RAM, and it turns eight shift-and-test iterations per byte into two
 * lookups. On a RAW2 frame the old loop ran 240 000 iterations — about 15 ms of
 * the receive path, on the BLE RX thread, per frame.
 *
 * Equivalence to the shift loop was checked exhaustively over the whole state
 * space (all 65536 CRC values x 256 input bytes) and against the standard
 * "123456789" -> 0x29B1 vector. */
static const uint16_t vs_crc16_nib[16] = {
    0x0000, 0x1021, 0x2042, 0x3063, 0x4084, 0x50A5, 0x60C6, 0x70E7,
    0x8108, 0x9129, 0xA14A, 0xB16B, 0xC18C, 0xD1AD, 0xE1CE, 0xF1EF,
};

static inline uint16_t vs_crc16_update(uint16_t crc, uint8_t b)
{
    crc = (uint16_t)((crc << 4) ^ vs_crc16_nib[((crc >> 12) ^ (b >> 4)) & 0x0Fu]);
    crc = (uint16_t)((crc << 4) ^ vs_crc16_nib[((crc >> 12) ^ (b & 0x0Fu)) & 0x0Fu]);
    return crc;
}

static void vs_reset_frame(void) {
    vs_prx = 0;
    vs_dec = 0;
    vs_dirty_y0 = INT_MAX;
    vs_dirty_y1 = -1;
    vs_rle.mode = 0;
    vs_rle.count = 0;
    vs_rle.val = 0;
    vs_crc = 0xFFFFu;
    vs_crc_rx = 0;
}

/* Bytes of one plane on the wire: the panel plane, or a quarter of it for a
 * half-resolution frame ((W/2) x (H/2), see VS_HALF_FLAG). */
static inline uint16_t vs_plane_bytes(void)
{
    return vs_half ? (uint16_t)(vs_fb / 4) : vs_fb;
}

/* Half-resolution frames land as 2x2 pixel blocks: each decoded byte (8
 * half-pixels) becomes two bytes in each of two framebuffer rows through a
 * nibble-doubling table. Doubling is linear over XOR, so a DRLE delta applied
 * this way on top of a half-res keyframe is exactly the doubled half-res
 * image — no extra buffer, no per-frame state beyond vs_dec. */
static const uint8_t vs_nib_dbl[16] = {
    0x00, 0x03, 0x0C, 0x0F, 0x30, 0x33, 0x3C, 0x3F,
    0xC0, 0xC3, 0xCC, 0xCF, 0xF0, 0xF3, 0xFC, 0xFF,
};

static inline void vs_write_byte(uint8_t b) {
    const bool dual = vs_type_is_dual(vs_type);
    const uint16_t plane = vs_plane_bytes();
    const uint16_t max_dec = dual ? (plane * 2) : plane;
    if (vs_dec >= max_dec) return;

    uint8_t *fb;
    uint16_t off = vs_dec;
    if (dual && off >= plane) {
        fb = fb_red();
        off -= plane;
    } else {
        fb = fb_bw();
    }

    if (fb) {   /* a B/W-only panel has no red plane: swallow that half */
        const bool delta = vs_type_is_delta(vs_type);
        const int stride = ssd1675a_width() / 8;   /* full-res bytes per row */
        if (!vs_half) {
            fb[off] = delta ? (fb[off] ^ b) : b;
            if (delta && b) {
                vs_mark_dirty(off / stride);
            }
        } else {
            const int hstride = stride / 2;
            const int hy = off / hstride, hx = off % hstride;
            uint8_t *p0 = fb + (2 * hy) * stride + 2 * hx;
            uint8_t *p1 = p0 + stride;
            const uint8_t d0 = vs_nib_dbl[b >> 4], d1 = vs_nib_dbl[b & 0x0F];
            if (delta) {
                p0[0] ^= d0; p0[1] ^= d1; p1[0] ^= d0; p1[1] ^= d1;
                if (b) {
                    vs_mark_dirty(2 * hy);
                    vs_mark_dirty(2 * hy + 1);
                }
            } else {
                p0[0] = d0;  p0[1] = d1;  p1[0] = d0;  p1[1] = d1;
            }
        }
    }
    vs_dec++;
}

static void vs_rle_feed(uint8_t b) {
    /* Drain pending run bytes first — they don't consume compressed input.
     * Without this, each run-continuation output would eat one real input
     * byte (the next instruction), corrupting the entire stream. */
    while (vs_rle.mode == 3) {
        vs_write_byte(vs_rle.val);
        if (--vs_rle.count == 0) { vs_rle.mode = 0; break; }
    }
    /* Now consume the actual compressed byte. */
    switch (vs_rle.mode) {
    case 0:
        if (b & 0x80) { vs_rle.count = (b & 0x7F) + 1; vs_rle.mode = 2; }
        else          { vs_rle.count = b + 1;            vs_rle.mode = 1; }
        break;
    case 1:
        vs_write_byte(b);
        if (--vs_rle.count == 0) vs_rle.mode = 0;
        break;
    case 2:
        vs_rle.val = b;
        vs_write_byte(b);
        if (--vs_rle.count == 0) vs_rle.mode = 0;
        else vs_rle.mode = 3;
        break;
    }
}

static void vs_flush_frame(void) {
    const bool dual = vs_type_is_dual(vs_type);
    const uint16_t max_dec = dual ? (vs_plane_bytes() * 2) : vs_plane_bytes();

    /* Flush any trailing run bytes that arrived at end of compressed stream. */
    if (!vs_type_is_raw(vs_type)) {
        while (vs_rle.mode == 3 && vs_dec < max_dec) {
            vs_write_byte(vs_rle.val);
            if (--vs_rle.count == 0) { vs_rle.mode = 0; break; }
        }
    }

    /* XOR checksum of the decoded framebuffer — legacy host integrity field,
     * superseded by the wire CRC-16 below (the `wc`/`rs` fields). Computing it
     * walks the whole framebuffer — 15 000 bytes on a 400x300 panel, 30 000
     * when both planes are live — and it sat right before the wait-for-BUSY,
     * so it landed squarely in the gap between frames. Only host_mode consumes
     * the value, so only host_mode pays for it; everyone else reports 00 and
     * gets the milliseconds back. */
    uint8_t crc = 0;
    if (host_mode) {
        const uint8_t *fb = fb_bw();
        for (int i = 0; i < vs_fb; i++) crc ^= fb[i];
        if (dual) {
            const uint8_t *fr = fb_red();   /* NULL on a B/W-only panel */
            for (int i = 0; fr && i < vs_fb; i++) crc ^= fr[i];
        }
    }

    /* Wire-CRC verdict (L0). A frame with no CRC trailer is trusted as before.
     * A CRC mismatch means the payload arrived corrupt; for a delta the in-place
     * XOR has already mutated the FB, so mark it poisoned and don't show it. */
    const bool crc_bad = vs_has_crc && (vs_crc != vs_crc_rx);
    if (crc_bad) {
        vs_poisoned = true;
    } else if (!vs_type_is_delta(vs_type)) {
        /* A clean full frame (RAW/RLE) overwrites every FB byte → heals. */
        vs_poisoned = false;
    }
    /* L1: while poisoned, even a clean delta can't be trusted (it built on a
     * corrupt FB), so skip it too and keep requesting a keyframe. The display
     * holds the last good frame until a full keyframe arrives. */
    const bool show = !crc_bad && !vs_poisoned;
    const bool want_resync = crc_bad || vs_poisoned;

    int32_t ms = 0, wait_ms = 0, spi_ms = 0;
    if (show) {
        /* Pipeline: wait for the PREVIOUS frame's refresh (triggered without
         * blocking, so it overlapped this frame's BLE transfer), then trigger
         * this one. ms includes the wait so the host sees real display timing;
         * w/s split it into the wave remainder and the SPI burst + trigger. */
        int64_t t0 = k_uptime_get();
        ssd1675a_wait_busy();
        int64_t t1 = k_uptime_get();
        display_manager_set_keep_on(true);
        display_manager_set_stream_write_red_plane(dual);
        if (vs_type_is_delta(vs_type) && !dual) {
            /* Only the rows the delta touched need to reach the controller;
             * an unchanged frame writes nothing and just refreshes. */
            display_manager_update_partial_rows_nowait(vs_dirty_y0, vs_dirty_y1);
        } else {
            display_manager_update_partial_nowait();
        }
        int64_t t2 = k_uptime_get();
        wait_ms = (int32_t)(t1 - t0);
        spi_ms = (int32_t)(t2 - t1);
        ms = (int32_t)(t2 - t0);
    }

    vs_frame_count++;
    /* Reset watchdog — host is alive and sending frames (skipped ones too). */
    k_work_reschedule(&vs_watchdog_work, K_MSEC(VS_WATCHDOG_MS));
    /* ACK: legacy fields (f/ms/dec/crc) plus the wire-CRC verdict wc and a
     * resync request rs=1 (host should send a full keyframe). Old hosts simply
     * ignore the two trailing fields. */
    const int rows = (vs_type_is_delta(vs_type) && !dual)
                         ? ((vs_dirty_y1 >= vs_dirty_y0) ? vs_dirty_y1 - vs_dirty_y0 + 1 : 0)
                         : ssd1675a_height();
    ble_printf("TELE:vs f=%d ms=%d dec=%d crc=%02x wc=%s rs=%d w=%d s=%d r=%d\r\n",
               vs_frame_count, (int)ms, (int)vs_dec, (unsigned)crc,
               vs_has_crc ? (crc_bad ? "bad" : "ok") : "na",
               want_resync ? 1 : 0, (int)wait_ms, (int)spi_ms, rows);
}

static void vs_process_byte(uint8_t b) {
    switch (vs_state) {
    case VS_IDLE:
        if      (b == VS_HDR1)  vs_state = VS_HDR2_WAIT;
        else if (b == VS_STOP1) vs_state = VS_STOP2_WAIT;
        break;
    case VS_HDR2_WAIT:
        vs_state = (b == VS_HDR2) ? VS_TYPE_RD : VS_IDLE;
        break;
    case VS_TYPE_RD:
        vs_has_crc = (b & VS_CRC_FLAG) != 0;
        vs_half    = (b & VS_HALF_FLAG) != 0;
        vs_type    = b & VS_TYPE_MASK & (uint8_t)~VS_HALF_FLAG;
        vs_state   = (vs_type <= VS_TYPE_DRLE2) ? VS_LEN_HI : VS_IDLE;
        break;
    case VS_LEN_HI:
        vs_plen  = (uint16_t)b << 8;
        vs_state = VS_LEN_LO;
        break;
    case VS_LEN_LO:
        vs_plen |= b;
        vs_reset_frame();
        /* Zero-length payload (e.g. an empty delta) still carries a CRC trailer
         * when the CRC bit is set, so route to the CRC states either way. */
        vs_state = (vs_plen > 0) ? VS_DATA
                 : (vs_has_crc ? VS_CRC_HI : VS_FLUSH_WAIT);
        break;
    case VS_DATA:
        vs_prx++;
        vs_crc = vs_crc16_update(vs_crc, b);  /* CRC covers raw payload bytes */
        if (vs_type_is_raw(vs_type)) vs_write_byte(b);
        else                         vs_rle_feed(b);
        if (vs_prx >= vs_plen)
            vs_state = vs_has_crc ? VS_CRC_HI : VS_FLUSH_WAIT;
        break;
    case VS_CRC_HI:
        vs_crc_rx = (uint16_t)b << 8;
        vs_state  = VS_CRC_LO;
        break;
    case VS_CRC_LO:
        vs_crc_rx |= b;
        vs_state   = VS_FLUSH_WAIT;
        break;
    case VS_FLUSH_WAIT:
        if (b == VS_FLUSH) vs_flush_frame();  /* flush_frame handles pending run drain */
        vs_state = VS_IDLE;
        break;
    case VS_STOP2_WAIT:
        if (b == VS_VIDEO_STOP2) {
            /* [CC DD] = video semantics: stop streaming and restore saver. */
            vs_exit_streaming(true);
            ble_printf("VSTREAM:stopped\r\n");
        } else if (b == VS_PHOTO_STOP2) {
            /* [CC DE] = still-photo semantics: stop streaming, power down
             * display/HV, but do not restart saver over the rendered photo. */
            vs_exit_streaming(false);
            ble_printf("VSTREAM:photo_stopped\r\n");
        }
        vs_state = VS_IDLE;
        break;
    }
}

