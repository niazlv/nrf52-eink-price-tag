void commands_on_disconnect(void) {
    /* If a video/animation stream was active, tear it down and restore the
     * screensaver — the stream content is gone and the device should not sit
     * frozen on a half-rendered frame.
     *
     * If the device is in still-photo / image mode (screensaver already off,
     * no active vstream) the user intentionally left a tonal image on the
     * display.  A BLE disconnect must NOT wake the screensaver and overwrite
     * that image — the panel is bistable and the picture persists without
     * power.  We only clean up the binary-stream machine state. */
    if (vstream_active) {
        vs_exit_streaming(true);   /* stream was running → restore saver */
    } else {
        /* No stream active: just reset protocol state, leave saver as-is. */
        ble_service_set_streaming_mode(false);
        display_manager_set_stream_write_red_plane(false);
        k_work_cancel_delayable(&vs_watchdog_work);
        vs_state = VS_IDLE;
    }

    /* Clear session-scoped virtual LUT slots — they are temporary experiments
     * defined over BLE and should not persist across reconnections. */
    ssd1675a_vlut_clear();

    /* Drop the per-connection auth so the next peer must authenticate again. */
    secauth_session_reset();

    /* Discard any half-received text line or opcode frame from the old link. */
    rx_len = 0;
    rx_discard = false;
    if (rx_slot) {
        k_fifo_put(&cmd_free, rx_slot);
        rx_slot = NULL;
    }
    opc_state = OPC_NONE;
    if (opc_slot) {
        k_fifo_put(&cmd_free, opc_slot);
        opc_slot = NULL;
    }

    /* The transfer, if any, went with the link. */
    dfu_set_busy(false);

    /* Commands the old link queued must not run against the new one. */
    for (struct cmd_slot *slot; (slot = k_fifo_get(&cmd_ready, K_NO_WAIT)) != NULL;) {
        k_fifo_put(&cmd_free, slot);
    }
}

/* Feed one byte into the binary opcode-frame state machine. On the final byte
 * the frame is dispatched through the shared opcode path. */
static void opc_finish(void)
{
    opc_state = OPC_NONE;
    if (!opc_slot) {
        return;                     /* frame was being discarded */
    }
    opc_slot->is_opcode = true;
    opc_slot->opcode = opc_opcode;
    k_fifo_put(&cmd_ready, opc_slot);
    opc_slot = NULL;
}

static void opc_feed_byte(uint8_t b)
{
    switch (opc_state) {
    case OPC_WANT_OP:
        opc_opcode = b;
        opc_slot = k_fifo_get(&cmd_free, K_NO_WAIT);
        if (!opc_slot) {
            ble_printf("BUSY:cmd\r\n");
        }
        opc_state = OPC_WANT_LEN;
        break;
    case OPC_WANT_LEN:
        opc_len = b;
        opc_idx = 0;
        if (opc_len == 0) {
            if (opc_slot) {
                opc_slot->line[0] = '\0';
            }
            opc_finish();
        } else {
            opc_state = OPC_WANT_PAYLOAD;
        }
        break;
    case OPC_WANT_PAYLOAD:
        if (opc_slot && opc_idx < RX_BUF_SIZE - 1) {
            opc_slot->line[opc_idx] = (char)b;
        }
        opc_idx++;
        if (opc_idx >= opc_len) {
            if (opc_slot) {
                uint8_t n = MIN(opc_len, (uint8_t)(RX_BUF_SIZE - 1));
                opc_slot->line[n] = '\0';
            }
            opc_finish();
        }
        break;
    default:
        opc_state = OPC_NONE;
        break;
    }
}

/* ── Command execution thread ───────────────────────────────────────────
 *
 * Text commands used to run right where the bytes arrived: inside the BLE
 * host's RX thread (bt_receive_cb -> commands_process). Every second a
 * handler spent on the panel was a second the host could not service the
 * link — CLEAN (~60 s) and NUKE (minutes) outlasted the phone's 30 s ATT
 * timeout, the phone dropped the connection, and the tag stayed invisible
 * until the handler returned and the disconnect callback finally ran. An
 * infinite TEST took the radio down with it for good.
 *
 * So the RX thread now only assembles lines and hands them over; this thread
 * runs them. A slow handler stalls the queue, not the radio: the link stays
 * up, SMP keeps flowing, and the next command is either queued (two deep) or
 * answered BUSY:cmd at once. REBOOT and SYSINFO are executed inline on the RX
 * thread so they work even while this thread is stuck in a dev loop — the
 * escape hatch that used to require pulling the battery. Binary paths
 * (vstream bytes, opcode frames) still run on the RX thread: they are fast by
 * construction. The mesh dispatch thread keeps its own path. */
static void cmd_thread(void *p1, void *p2, void *p3)
{
    ARG_UNUSED(p1); ARG_UNUSED(p2); ARG_UNUSED(p3);

    for (int i = 0; i < CMD_QUEUE_DEPTH; i++) {
        k_fifo_put(&cmd_free, &cmd_slots[i]);
    }
    while (1) {
        struct cmd_slot *slot = k_fifo_get(&cmd_ready, K_FOREVER);

        if (slot->is_opcode) {
            cmd_dispatch_opcode(slot->opcode, slot->line, CMD_ORIGIN_NUS);
        } else {
            dispatch_line(slot->line);
        }
        slot->is_opcode = false;
        k_fifo_put(&cmd_free, slot);
    }
}
K_THREAD_DEFINE(cmd_tid, 1280, cmd_thread, NULL, NULL, NULL, 7, 0, 0);

/* Whatever must keep working while the command thread is busy for minutes. */
static bool inline_on_rx_thread(const char *line)
{
    return strcmp(line, "REBOOT") == 0 || strncmp(line, "SYSINFO", 7) == 0;
}

static void enqueue_line(struct cmd_slot *slot)
{
    slot->is_opcode = false;
    if (inline_on_rx_thread(slot->line)) {
        dispatch_line(slot->line);
        k_fifo_put(&cmd_free, slot);
        return;
    }
    k_fifo_put(&cmd_ready, slot);
}

void commands_process(const void *data, uint16_t len)
{
    const uint8_t *p = (const uint8_t *)data;
    for (uint16_t i = 0; i < len; i++) {
        if (vstream_active) {
            vs_process_byte(p[i]);
            continue;
        }
        if (opc_state != OPC_NONE) {
            opc_feed_byte(p[i]);
            continue;
        }
        /* A frame sentinel is only valid at a line boundary, so it can never be
         * mistaken for a byte inside a half-typed text command. */
        if (rx_len == 0 && p[i] == OPC_MAGIC) {
            opc_state = OPC_WANT_OP;
            continue;
        }
        char c = (char)p[i];
        if (c == '\r') continue;
        if (rx_discard) {
            /* Both slots are busy behind a slow command: this line is lost;
             * the BUSY:cmd already went out when it started. */
            if (c == '\n') rx_discard = false;
            continue;
        }
        if (!rx_slot) {
            if (c == '\n') continue;          /* empty line, nothing to queue */
            rx_slot = k_fifo_get(&cmd_free, K_NO_WAIT);
            if (!rx_slot) {
                rx_discard = true;
                ble_printf("BUSY:cmd\r\n");
                continue;
            }
            rx_len = 0;
        }
        if (c == '\n') {
            rx_slot->line[rx_len] = '\0';
            rx_len = 0;
            if (rx_slot->line[0] != '\0') {
                enqueue_line(rx_slot);
            } else {
                k_fifo_put(&cmd_free, rx_slot);
            }
            rx_slot = NULL;
        } else if (rx_len < RX_BUF_SIZE - 1) {
            rx_slot->line[rx_len++] = c;
        }
    }
}
